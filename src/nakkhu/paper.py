"""``nakkhu paper numbers``: manuscript numbers generated from logged artifacts (plan 012 Step 2).

A declarative table (``configs/paper/numbers.yaml``) maps each LaTeX macro name to a source file,
a selector into it and a status. The command reads every source, writes one ``\\newcommand`` per
entry into ``mdpi-journal-paper/numbers.tex`` and puts the source, its SHA-256, the selector, the
raw value and the status in a comment above it. The output carries no timestamp, so ``--check``
can tell whether the manuscript's numbers are stale.

Sources are files under ``artifacts/`` (SHA-256 checked against ``artifacts/INDEX.yaml``),
``configs/`` or a complete run under ``runs/``. Only ``final`` values are printed. ``val`` and
``prov`` values print a ``\\todo{}`` (or, with ``--draft``, the value in a visible marker), and
an entry without a source (``missing``) always prints a ``\\todo{}``.

An entry may instead give ``values`` (a list of ``{source, select[, field]}`` whose selections
are concatenated) or ``expr`` (arithmetic over earlier entries' raw values). ``aggregate`` is
``count``, ``mean``, ``sd`` (ddof 1), ``min`` or ``max``; ``field`` maps a selected list of
mappings to one field.

Selector grammar (dot-separated steps): ``key`` (mapping key), ``[3]`` / ``[-1]`` (list index)
and ``[col=value,col2=value2]`` (the one list element whose fields equal the given strings);
``.`` alone selects the whole document.
CSV files load as a list of row mappings, e.g. ``[inventory=google_v3].n_final``.
"""

from __future__ import annotations

import argparse
import ast
import csv
import hashlib
import io
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from nakkhu.artifacts import load_index
from nakkhu.config import Project
from nakkhu.paths import PathError, ProjectPaths
from nakkhu.runs import find_run_dir, journal_status

NUMBERS_CONFIG = "configs/paper/numbers.yaml"
STATUSES = ("final", "val", "prov", "missing")
SOURCE_ROOTS = ("artifacts", "configs", "runs")
AGGREGATES = ("count", "mean", "sd", "min", "max")
_MACRO = re.compile(r"[A-Za-z]+")
_STEP = re.compile(r"\[(?P<bracket>[^\]]*)\]|(?P<key>[^.\[\]]+)|(?P<dot>\.)")
_LATEX_SPECIAL = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#",
                  "$": r"\$", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
                  "{": r"\{", "}": r"\}"}

HEADER = """\
% Generated by `uv run nakkhu paper numbers` from nakkhu/{config}. Do not edit by hand:
% add or change an entry in that table and rerun the command.
% Each macro is preceded by: name | status | source @sha256 prefix | selector = raw value.
% Only `final` values are printed; val/prov values print \\todo{{}} unless --draft was given.
% Mode: {mode}.
\\providecommand{{\\todo}}[1]{{\\textcolor{{red}}{{\\textbf{{[TODO:}} #1\\textbf{{]}}}}}}
\\providecommand{{\\draftnum}}[2]{{\\textcolor{{blue}}{{\\textbf{{[#1]}}\\textsuperscript{{#2}}}}}}
"""


class NumbersError(RuntimeError):
    """The numbers table or one of its sources is invalid."""


@dataclass(frozen=True)
class Number:
    name: str
    status: str
    tex: str
    comment: str


# --- selectors ------------------------------------------------------------------------------


def parse_selector(selector: str) -> list[tuple[str, Any]]:
    """Split a selector into ``("key", name)``, ``("index", i)`` and ``("match", {...})`` steps."""
    if selector.strip() == ".":
        return []  # the whole document
    steps: list[tuple[str, Any]] = []
    pos = 0
    while pos < len(selector):
        match = _STEP.match(selector, pos)
        if match is None:
            raise NumbersError(f"selector {selector!r}: cannot parse at position {pos}")
        pos = match.end()
        if match.group("dot") is not None:
            continue
        if match.group("key") is not None:
            steps.append(("key", match.group("key").strip()))
            continue
        inner = match.group("bracket").strip()
        if re.fullmatch(r"-?\d+", inner):
            steps.append(("index", int(inner)))
            continue
        conditions: dict[str, str] = {}
        for part in inner.split(","):
            if "=" not in part:
                raise NumbersError(f"selector {selector!r}: [{inner}] is neither an index nor "
                                   "a list of field=value conditions")
            field, value = part.split("=", 1)
            conditions[field.strip()] = value.strip()
        steps.append(("match", conditions))
    if not steps:
        raise NumbersError("empty selector")
    return steps


def select(document: Any, selector: str) -> Any:
    """Apply ``selector`` to a loaded JSON/YAML/CSV document."""
    value = document
    for kind, arg in parse_selector(selector):
        if kind == "key":
            if not isinstance(value, dict) or arg not in value:
                raise NumbersError(f"selector {selector!r}: key {arg!r} not found")
            value = value[arg]
        elif kind == "index":
            if not isinstance(value, list) or not -len(value) <= arg < len(value):
                raise NumbersError(f"selector {selector!r}: index {arg} out of range")
            value = value[arg]
        else:
            if not isinstance(value, list):
                raise NumbersError(f"selector {selector!r}: {arg} applied to a non-list")
            hits = [item for item in value if isinstance(item, dict)
                    and all(str(item.get(k)) == v for k, v in arg.items())]
            if len(hits) != 1:
                raise NumbersError(f"selector {selector!r}: {arg} matches {len(hits)} "
                                   "elements, expected exactly 1")
            value = hits[0]
    return value


# --- sources --------------------------------------------------------------------------------


@dataclass(frozen=True)
class Source:
    rel: str
    sha256: str
    document: Any
    from_csv: bool


def _load_document(path: Path) -> tuple[Any, bool]:
    text = path.read_text(encoding="utf-8")
    suffix = path.suffix.lower()
    if suffix in (".json", ".geojson"):
        return json.loads(text), False
    if suffix in (".yaml", ".yml"):
        return yaml.safe_load(text), False
    if suffix == ".csv":
        return list(csv.DictReader(io.StringIO(text))), True
    raise NumbersError(f"{path.name}: unsupported source type {suffix!r} (json, yaml, csv)")


class SourceCache:
    """Loads each source once and checks its provenance."""

    def __init__(self, paths: ProjectPaths) -> None:
        self.paths = paths
        self._index: dict[str, str] | None = None
        self._cache: dict[str, Source] = {}

    def _index_sha(self, rel_to_artifacts: str) -> str | None:
        if self._index is None:
            self._index = {entry["path"]: entry["sha256"]
                           for entry in load_index(self.paths)["artifacts"]}
        return self._index.get(rel_to_artifacts)

    def get(self, source: str) -> Source:
        if source in self._cache:
            return self._cache[source]
        try:
            path = self.paths.resolve(source)
            rel = self.paths.relative(path)
        except PathError as error:
            raise NumbersError(f"source {source!r}: {error}") from error
        top = rel.split("/", 1)[0]
        if top not in SOURCE_ROOTS:
            raise NumbersError(f"source {source!r} must lie under {', '.join(SOURCE_ROOTS)}/")
        if not path.is_file():
            raise NumbersError(f"source {source!r} does not exist")
        data = path.read_bytes()
        sha = hashlib.sha256(data).hexdigest()
        if top == "artifacts":
            indexed = self._index_sha(rel.split("/", 1)[1])
            if indexed is None:
                raise NumbersError(f"source {rel} is not in artifacts/INDEX.yaml")
            if indexed != sha:
                raise NumbersError(f"source {rel}: SHA-256 {sha[:12]} differs from INDEX.yaml "
                                   f"{indexed[:12]}")
        elif top == "runs":
            run_dir = find_run_dir(path, self.paths)
            if run_dir is None:
                raise NumbersError(f"source {rel} is not inside runs/<stage>/<run_id>/")
            status = journal_status(run_dir)
            if status != "complete":
                raise NumbersError(f"source {rel}: run journal is {status}, not complete")
        document, from_csv = _load_document(path)
        loaded = Source(rel=rel, sha256=sha, document=document, from_csv=from_csv)
        self._cache[source] = loaded
        return loaded


# --- formatting -----------------------------------------------------------------------------


def _coerce(value: Any) -> Any:
    """CSV cells are strings: read integers and floats as numbers."""
    if not isinstance(value, str):
        return value
    for kind in (int, float):
        try:
            return kind(value)
        except ValueError:
            pass
    return value


def latex_escape(text: str) -> str:
    return "".join(_LATEX_SPECIAL.get(char, char) for char in text)


def format_value(value: Any, fmt: str) -> str:
    """Python ``str.format`` the value, escape it for LaTeX, typeset thousands as ``{,}``."""
    try:
        text = fmt.format(value)
    except (ValueError, TypeError) as error:
        raise NumbersError(f"cannot format {value!r} with {fmt!r}: {error}") from error
    text = latex_escape(text)
    if isinstance(value, int | float) and not isinstance(value, bool):
        text = text.replace(",", "{,}")
    return text


def _raw(value: Any) -> str:
    text = json.dumps(value, ensure_ascii=False) if not isinstance(value, str) else value
    return text.replace("\n", " ")


# --- table ----------------------------------------------------------------------------------


def load_table(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise NumbersError(f"numbers table {path} does not exist")
    document = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(document, dict) or not isinstance(document.get("numbers"), dict):
        raise NumbersError(f"{path.name}: expected a mapping with a `numbers` mapping")
    return document


def _select_one(name: str, spec: dict[str, Any], sources: SourceCache) -> tuple[Any, str]:
    """Select from one {source, select[, field]} spec; ``field`` maps over a selected list."""
    if "select" not in spec:
        raise NumbersError(f"{name}: an entry with a source needs `select`")
    source = sources.get(spec["source"])
    value = select(source.document, spec["select"])
    if source.from_csv:
        value = _coerce(value)
    provenance = f"{source.rel} @{source.sha256[:12]} | {spec['select']}"
    field = spec.get("field")
    if field is not None:
        if not isinstance(value, list) or not all(isinstance(v, dict) and field in v
                                                  for v in value):
            raise NumbersError(f"{name}: `field` {field!r} needs a list of mappings with it")
        value = [_coerce(v[field]) if source.from_csv else v[field] for v in value]
        provenance += f"[*].{field}"
    return value, provenance


def _numeric_list(name: str, value: Any, aggregate: str) -> list[float]:
    if not isinstance(value, list) or not value or not all(
            isinstance(v, int | float) and not isinstance(v, bool) for v in value):
        raise NumbersError(f"{name}: {aggregate} needs a non-empty list of numbers")
    return [float(v) for v in value]


def _aggregate(name: str, value: Any, aggregate: str) -> Any:
    if aggregate not in AGGREGATES:
        raise NumbersError(f"{name}: aggregate must be one of {AGGREGATES}")
    if aggregate == "count":
        if not isinstance(value, list | dict):
            raise NumbersError(f"{name}: count needs a list or mapping")
        return len(value)
    values = _numeric_list(name, value, aggregate)
    if aggregate == "mean":
        return sum(values) / len(values)
    if aggregate == "min":
        return min(values)
    if aggregate == "max":
        return max(values)
    if len(values) < 2:  # sd: sample standard deviation (ddof = 1), as in the seed summaries
        raise NumbersError(f"{name}: sd needs at least two values")
    mean = sum(values) / len(values)
    return (sum((v - mean) ** 2 for v in values) / (len(values) - 1)) ** 0.5


_EXPR_NODES = (ast.Expression, ast.BinOp, ast.UnaryOp, ast.Constant, ast.Name, ast.Load,
               ast.Add, ast.Sub, ast.Mult, ast.Div, ast.USub, ast.UAdd)


def _evaluate(name: str, expr: str, known: dict[str, Any]) -> tuple[float, list[str]]:
    """Evaluate arithmetic over earlier macros' raw values (+ - * /, numbers, macro names)."""
    try:
        tree = ast.parse(expr, mode="eval")
    except SyntaxError as error:
        raise NumbersError(f"{name}: cannot parse expr {expr!r}") from error
    used: list[str] = []
    for node in ast.walk(tree):
        if not isinstance(node, _EXPR_NODES):
            raise NumbersError(f"{name}: expr {expr!r} may only use + - * /, numbers and macros")
        if isinstance(node, ast.Name):
            if node.id not in known:
                raise NumbersError(f"{name}: expr uses {node.id!r}, which is not an earlier "
                                   "entry with a numeric value")
            used.append(node.id)

    def ev(node: ast.AST) -> float:
        if isinstance(node, ast.Expression):
            return ev(node.body)
        if isinstance(node, ast.Constant) and isinstance(node.value, int | float):
            return float(node.value)
        if isinstance(node, ast.Name):
            return float(known[node.id])
        if isinstance(node, ast.UnaryOp):
            return -ev(node.operand) if isinstance(node.op, ast.USub) else ev(node.operand)
        if isinstance(node, ast.BinOp):
            a, b = ev(node.left), ev(node.right)
            if isinstance(node.op, ast.Add):
                return a + b
            if isinstance(node.op, ast.Sub):
                return a - b
            if isinstance(node.op, ast.Mult):
                return a * b
            if b == 0:
                raise NumbersError(f"{name}: division by zero in {expr!r}")
            return a / b
        raise NumbersError(f"{name}: unsupported element in {expr!r}")

    return ev(tree), used


def _resolve_entry(name: str, entry: dict[str, Any], sources: SourceCache,
                   known: dict[str, Any] | None = None) -> tuple[Any, str]:
    """Return (value, provenance text) for one entry with a source, `values` or `expr`."""
    if "expr" in entry:
        value, used = _evaluate(name, str(entry["expr"]), known or {})
        return value, f"expr {entry['expr']} over {', '.join(used) or 'constants'}"
    if "values" in entry:
        specs = entry["values"]
        if not isinstance(specs, list) or not specs:
            raise NumbersError(f"{name}: `values` must be a non-empty list of {{source, select}}")
        value: Any = []
        parts: list[str] = []
        for spec in specs:
            one, prov = _select_one(name, spec, sources)
            value.extend(one if isinstance(one, list) else [one])
            parts.append(prov)
        provenance = " ; ".join(parts)
    else:
        value, provenance = _select_one(name, entry, sources)
    aggregate = entry.get("aggregate")
    if aggregate is not None:
        value = _aggregate(name, value, aggregate)
        provenance += f" ({aggregate})"
    multiply = entry.get("multiply_by")
    if multiply is not None:
        other = sources.get(multiply["source"])
        factor = select(other.document, multiply["select"])
        if other.from_csv:
            factor = _coerce(factor)
        if not isinstance(value, int | float) or not isinstance(factor, int | float):
            raise NumbersError(f"{name}: multiply_by needs two numbers")
        provenance += f" x {other.rel} @{other.sha256[:12]} | {multiply['select']} = {factor!r}"
        value = value * factor
    scale = entry.get("scale")
    if scale is not None:
        if not isinstance(value, int | float):
            raise NumbersError(f"{name}: scale needs a number")
        provenance += f" x {scale!r}"
        value = value * scale
    return value, provenance


def build_numbers(paths: ProjectPaths, table: dict[str, Any], *, draft: bool) -> list[Number]:
    sources = SourceCache(paths)
    numbers: list[Number] = []
    known: dict[str, Any] = {}          # raw numeric values of earlier entries (for `expr`)
    known_status: dict[str, str] = {}
    for name, entry in table["numbers"].items():
        if not isinstance(name, str) or not _MACRO.fullmatch(name):
            raise NumbersError(f"macro name {name!r} must be letters only (a LaTeX command)")
        if not isinstance(entry, dict):
            raise NumbersError(f"{name}: entry must be a mapping")
        status = entry.get("status")
        has_source = any(entry.get(key) is not None for key in ("source", "values", "expr"))
        if status not in STATUSES:
            raise NumbersError(f"{name}: status must be one of {STATUSES}, got {status!r}")
        if (status == "missing") == has_source:
            raise NumbersError(f"{name}: status `missing` exactly when there is no source")
        note = str(entry.get("note", "")).strip()
        if not has_source:
            tex = rf"\todo{{\texttt{{{name}}}: no logged artifact}}"
            comment = f"{name} | missing | no artifact" + (f" | {note}" if note else "")
        else:
            if "expr" in entry and status == "final":
                _, used = _evaluate(name, str(entry["expr"]), known)
                weaker = [u for u in used if known_status[u] != "final"]
                if weaker:
                    raise NumbersError(f"{name}: a final expr cannot use non-final {weaker}")
            value, provenance = _resolve_entry(name, entry, sources, known)
            if isinstance(value, int | float) and not isinstance(value, bool):
                known[name], known_status[name] = value, status
            text = format_value(value, str(entry.get("format", "{}")))
            if status == "final":
                tex = text
            elif draft:
                tex = rf"\draftnum{{{text}}}{{{status}}}"
            else:
                tex = rf"\todo{{\texttt{{{name}}} ({status})}}"
            comment = f"{name} | {status} | {provenance} = {_raw(value)}"
            if note:
                comment += f" | {note}"
        numbers.append(Number(name=name, status=status, tex=tex, comment=comment))
    return numbers


def render(numbers: list[Number], *, draft: bool) -> str:
    mode = "draft (val/prov values shown in \\draftnum markers)" if draft else "final"
    lines = [HEADER.format(config=NUMBERS_CONFIG, mode=mode)]
    for number in numbers:
        lines.append(f"% {number.comment}")
        lines.append(rf"\newcommand{{\{number.name}}}{{{number.tex}}}")
    return "\n".join(lines) + "\n"


def output_path(paths: ProjectPaths, table: dict[str, Any], override: str | None) -> Path:
    target = override or table.get("output")
    if not target:
        raise NumbersError("no output path: set `output` in the table or pass --output")
    path = Path(target)
    path = path if path.is_absolute() else paths.root / path
    if path.suffix != ".tex":
        raise NumbersError(f"output {target!r} must be a .tex file")
    return path.resolve()


def run_numbers(project: Project, *, config: str = NUMBERS_CONFIG, output: str | None = None,
                draft: bool = False, check: bool = False) -> tuple[Path, list[Number], bool]:
    """Generate the numbers file. Returns (path, numbers, up_to_date). ``check`` never writes."""
    table = load_table(project.paths.resolve(config))
    numbers = build_numbers(project.paths, table, draft=draft)
    text = render(numbers, draft=draft)
    path = output_path(project.paths, table, output)
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    up_to_date = current == text
    if not check and not up_to_date:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return path, numbers, up_to_date


# --- CLI ------------------------------------------------------------------------------------


def _numbers_cmd(project: Project, args: argparse.Namespace) -> int:
    try:
        path, numbers, up_to_date = run_numbers(
            project, config=args.table, output=args.output, draft=args.draft, check=args.check)
    except NumbersError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    counts = {status: sum(n.status == status for n in numbers) for status in STATUSES}
    print(f"{len(numbers)} macros: " + ", ".join(f"{v} {k}" for k, v in counts.items()))
    for number in numbers:
        if number.status != "final":
            print(f"  {number.status:7s} \\{number.name}")
    if args.check:
        print(f"{path}: {'up to date' if up_to_date else 'STALE'}")
        return 0 if up_to_date else 1
    print(f"{'unchanged' if up_to_date else 'wrote'} {path}")
    return 0


def register(commands: Any) -> None:
    paper = commands.add_parser("paper", help="manuscript support (plan 012)")
    sub = paper.add_subparsers(dest="paper_command", required=True, metavar="ACTION")
    numbers = sub.add_parser("numbers", help="write mdpi-journal-paper/numbers.tex from "
                             f"artifacts via {NUMBERS_CONFIG}")
    numbers.add_argument("--table", default=NUMBERS_CONFIG,
                         help=f"numbers table (default: {NUMBERS_CONFIG})")
    numbers.add_argument("--output", help="output .tex (default: the table's `output`)")
    numbers.add_argument("--draft", action="store_true",
                         help="print val/prov values inside a visible \\draftnum marker")
    numbers.add_argument("--check", action="store_true",
                         help="do not write; exit 1 if the output file is stale")
    numbers.set_defaults(func=_numbers_cmd)

    from nakkhu.paper_export import register as register_export

    register_export(sub)
