from pathlib import Path

import pytest

from nakkhu.cli import main
from nakkhu.paper_export import (
    ExportError,
    expand_numbers,
    export,
    load_macros,
    scrub_pdf_info,
    strip_bib_comments,
    strip_comments,
)

NUMBERS = r"""% Generated by `uv run nakkhu paper numbers` from nakkhu/configs/paper/numbers.yaml.
\providecommand{\todo}[1]{\textcolor{red}{\textbf{[TODO:} #1\textbf{]}}}
\providecommand{\draftnum}[2]{\textcolor{blue}{\textbf{[#1]}\textsuperscript{#2}}}

% numA | final | artifacts/demo/summary.json @0123456789ab | a = 14202
\newcommand{\numA}{14{,}202}
% numPct | final | artifacts/demo/summary.json @0123456789ab | pct = 4.5
\newcommand{\numPct}{4.5\,\%}
% numNeg | final | runs/demo/x.json @0123456789ab | neg = -0.12
\newcommand{\numNeg}{\textminus 0.12}
% numWord | final | configs/demo.yaml @0123456789ab | sign = minus
\newcommand{\numWord}{\textminus}
% numTodo | val | artifacts/demo/summary.json @0123456789ab | t = 1
\newcommand{\numTodo}{\todo{\texttt{numTodo} (val)}}
% numDraft | prov | artifacts/demo/summary.json @0123456789ab | d = 2
\newcommand{\numDraft}{\draftnum{2}{prov}}
"""

MACROS = load_macros(NUMBERS)


def _expand(tex: str) -> str:
    return expand_numbers(tex, MACROS)[0]


def test_load_macros_reads_values_verbatim():
    assert MACROS["numA"] == "14{,}202"
    assert MACROS["numPct"] == r"4.5\,\%"
    assert len(MACROS) == 6
    with pytest.raises(ExportError, match="not a one-line"):
        load_macros(r"\def\numX{1}")


@pytest.mark.parametrize("tex, expected", [
    (r"\numA{} buildings", "14{,}202 buildings"),
    (r"\numA buildings", "14{,}202buildings"),          # TeX swallows the space
    (r"\numA   & next", "14{,}202& next"),
    (r"\numA~m", "14{,}202~m"),
    (r"\numA\,km", r"14{,}202\,km"),
    (r"{\numA}", "{14{,}202}"),
    (r"(\numA), \numA.", "(14{,}202), 14{,}202."),
    (r"\numA \\", r"14{,}202\\"),
    (r"\numPct{} of", r"4.5\,\% of"),
    (r"$\numNeg$", r"$\textminus 0.12$"),
    ("\\numA\nnext", "14{,}202%\nnext"),                # end of line after a control word
    ("\\numA  \n\nnext", "14{,}202%\n\nnext"),          # ... and the paragraph break stays
    (r"\numWord{}x", r"\textminus{}x"),                  # value ending in a control word
    (r"\numWord x", r"\textminus{}x"),
    (r"\numWord~x", r"\textminus~x"),
    (r"\\numA", r"\\numA"),                              # a line break, then the text "numA"
    (r"\numberwithin{equation}{section}", r"\numberwithin{equation}{section}"),
])
def test_expand_spacing(tex: str, expected: str):
    assert _expand(tex) == expected


def test_expand_counts_and_failures():
    text, used, replacements = expand_numbers(r"\numA{} and \numA, \numPct", MACROS)
    assert (used, replacements) == ({"numA", "numPct"}, 3)
    with pytest.raises(ExportError, match=r"undefined number macros: \\numMissing"):
        expand_numbers(r"\numA{} \numMissing{}", MACROS)
    with pytest.raises(ExportError, match="numTodo"):
        expand_numbers(r"\numTodo{}", MACROS)
    with pytest.raises(ExportError, match="numDraft"):
        expand_numbers(r"\numDraft{}", MACROS)
    assert expand_numbers(r"\numA{}", MACROS)[0] == "14{,}202"  # unused todos do not matter


def test_strip_comments():
    tex = ("% header with artifacts/x.json\n"
           "\\address{%\n"
           "  50\\% of 3\\,\\%  % trailing note, runs/abc\n"
           "line\\\\% comment after a line break\n"
           "   % indented comment\n"
           "\n"
           "end\n")
    assert strip_comments(tex) == ("\\address{%\n"
                                   "  50\\% of 3\\,\\%  %\n"
                                   "line\\\\%\n"
                                   "\n"
                                   "end\n")
    with pytest.raises(ExportError, match="verb"):
        strip_comments("\\verb|%| x\n")


def test_strip_bib_comments_and_pdf_info():
    bib = "% notes (plans/x.md)\n@article{a,\n  title = {A},\n  note = {x}\n}\n% more\n"
    assert strip_bib_comments(bib) == "@article{a,\n  title = {A},\n  note = {x}\n}\n"
    pdf = b"1 0 obj\n<< /Creator (floodfig) /Subject ([final] artifacts/a\\).csv) >>\nendobj\n"
    scrubbed = scrub_pdf_info(pdf)
    assert len(scrubbed) == len(pdf) and b"artifacts/" not in scrubbed
    assert b"/Creator (floodfig)" in scrubbed


def _manuscript(tmp_path: Path, body: str = r"We mapped \numA{} buildings (\numPct)." + "\n"):
    paper = tmp_path / "paper"
    (paper / "Definitions").mkdir(parents=True)
    (paper / "Definitions" / "demo.cls").write_text("% class\n", encoding="utf-8")
    (paper / "figures").mkdir()
    (paper / "figures" / "map.pdf").write_bytes(b"%PDF-1.4\n<< /Subject (artifacts/a.csv) >>\n")
    (paper / "figures" / "unused.pdf").write_bytes(b"%PDF-1.4\n")
    (paper / "ref.bib").write_text("% internal note, plans/refs.md\n@misc{k,\n  title = {K}\n}\n",
                                   encoding="utf-8")
    (paper / "numbers.tex").write_text(NUMBERS, encoding="utf-8")
    (paper / "Main.tex").write_text(
        "\\documentclass[article]{Definitions/demo}\n"
        "% Numerical results (artifacts/INDEX.yaml).\n"
        "\\input{numbers}\n"
        "\\begin{document}\n" + body +
        "\\includegraphics[width=\\linewidth]{figures/map}\n"
        "\\bibliography{ref}\n"
        "\\end{document}\n", encoding="utf-8")
    return paper


def test_export_writes_a_standalone_copy(tmp_path: Path):
    paper = _manuscript(tmp_path)
    before = (paper / "Main.tex").read_bytes(), (paper / "numbers.tex").read_bytes()
    result = export(paper / "Main.tex", paper / "numbers.tex", paper / "submission")
    out = paper / "submission"
    text = (out / "Main.tex").read_text(encoding="utf-8")
    assert "We mapped 14{,}202 buildings (4.5\\,\\%)." in text
    assert "\\input" not in text and "\\num" not in text and "%" not in text.replace("\\%", "")
    assert (out / "Definitions" / "demo.cls").is_file()
    assert (out / "figures" / "map.pdf").is_file()
    assert not (out / "figures" / "unused.pdf").exists()
    assert b"artifacts/" not in (out / "figures" / "map.pdf").read_bytes()
    assert (out / "ref.bib").read_text(encoding="utf-8") == "@misc{k,\n  title = {K}\n}\n"
    assert (result.replacements, result.macros_used, result.todos) == (2, 2, [])
    assert ((paper / "Main.tex").read_bytes(), (paper / "numbers.tex").read_bytes()) == before
    # a second export replaces the first
    export(paper / "Main.tex", paper / "numbers.tex", paper / "submission")


def test_export_refusals(tmp_path: Path):
    paper = _manuscript(tmp_path, body="Funded by grant \\todo{grant number}.\n")
    assert export(paper / "Main.tex", paper / "numbers.tex",
                  paper / "out").todos == ["\\todo{grant number}"]
    with pytest.raises(ExportError, match="holds no previous export"):
        export(paper / "Main.tex", paper / "numbers.tex", paper / "figures")
    with pytest.raises(ExportError, match="overwrite the working manuscript"):
        export(paper / "Main.tex", paper / "numbers.tex", paper)
    paper = _manuscript(tmp_path / "b", body="See https://x.org/runs/1 for \\numA{}.\n")
    with pytest.raises(ExportError, match="runs/"):
        export(paper / "Main.tex", paper / "numbers.tex", paper / "submission")


def test_cli_export(tmp_path: Path, root: Path, capsys):
    paper = _manuscript(tmp_path)
    args = ["--root", str(root), "paper", "export", "--numbers", str(paper / "numbers.tex")]
    assert main(args) == 0
    assert "2 number macros inlined" in capsys.readouterr().out
    assert (paper / "submission" / "Main.tex").is_file()
    (paper / "Main.tex").write_text("\\input{numbers}\n\\numNope{}\n", encoding="utf-8")
    assert main(args) == 1
    assert "numNope" in capsys.readouterr().err
